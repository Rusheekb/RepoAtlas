/**
 * Pick the Shiki grammar for a file: by the analysis' display language first, then by file name or extension.
 * Returns null when we don't have a grammar (the code is then shown as plain text).
 */
export function grammarFor(language: string | null | undefined, path?: string): GrammarId | null {
  if (language && language in BY_LANGUAGE) return BY_LANGUAGE[language]
  if (!path) return null
  const name = basename(path).toLowerCase()
  if (name in BY_NAME) return BY_NAME[name]
  if (name.startsWith('dockerfile') || name.endsWith('.dockerfile')) return 'dockerfile'
  if (name.startsWith('.env')) return 'dotenv'
  const ext = extname(path)
  return ext in BY_EXTENSION ? BY_EXTENSION[ext] : null
}

